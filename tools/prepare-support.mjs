// Build the same source-pinned bundle as support_knowledge.py, without a Python build dependency.
import { readFileSync, writeFileSync, mkdirSync, realpathSync, readdirSync } from 'node:fs';
import { resolve, dirname, relative, isAbsolute } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const canonical = v => JSON.stringify(v, (_, value) => value && typeof value === 'object' && !Array.isArray(value) ? Object.fromEntries(Object.keys(value).sort().map(k => [k,value[k]])) : value);
const hash = v => createHash('sha256').update(v).digest('hex');
const read = path => {
  if (path.includes('\\') || path.includes(':') || path.split('/').includes('..')) throw Error('Invalid source path');
  const full = realpathSync(resolve(root,path)), rel = relative(realpathSync(root),full);
  if (rel.startsWith('..') || isAbsolute(rel)) throw Error('Source outside repository');
  return readFileSync(full,'utf8').replace(/\r\n/g,'\n');
};
const contract = JSON.parse(read('support/catalog.json'));
if(contract.surface==='website') {
  const listed=new Set(contract.features.filter(f=>f.body==='@html-main').flatMap(f=>f.sources));
  for(const name of readdirSync(resolve(root,'youle-ai_index/help')).sort()) {
    const path='youle-ai_index/help/'+name;if(!name.endsWith('.html') || listed.has(path))continue;
    const slug=name.slice(0,-5);
    contract.features.push({id:'help-'+slug,title:slug,body:'@html-main',category:slug,locale:'zh-CN',status:'approved',requires_login:false,platforms:['website'],actions:{},sources:[path]});
  }
}
for (const f of contract.features) if (f.body === '@html-main') {
  if (contract.surface !== 'website' || !f.sources[0].startsWith('youle-ai_index/help/') || !f.sources[0].endsWith('.html')) throw Error('Invalid help source');
  const main=read(f.sources[0]).match(/<main\b[^>]*>([\s\S]*?)<\/main>/i);if(!main)throw Error('No help main content');
  const entities={amp:'&',lt:'<',gt:'>',quot:'"',apos:"'",nbsp:' '};
  f.body=main[1].replace(/<(script|style|nav|video|button)\b[^>]*>[\s\S]*?<\/\1>/gi,' ').replace(/<[^>]+>/g,' ')
    .replace(/&(#x[0-9a-fA-F]+|#\d+|amp|lt|gt|quot|apos|nbsp);/g,(all,key)=>key.startsWith('#x')?String.fromCodePoint(parseInt(key.slice(2),16)):key.startsWith('#')?String.fromCodePoint(Number(key.slice(1))):entities[key]||all)
    .replace(/\s+/g,' ').trim();
  if(!f.body || [...f.body].length>16000)throw Error('Help article too large; split it explicitly');
}

const repositories = {windows:'cuirenjie/haolo_windows_web3',mobile:'cuirenjie/haolo_android_web3',website:'cuirenjie/haolo_front_web3'};
if (contract.repository !== repositories[contract.surface] || contract.schema_version !== 1) throw Error('Wrong support repository');
const source_sha = execFileSync('git',['-C',root,'rev-parse','HEAD'],{encoding:'utf8'}).trim();
const version = contract.surface === 'windows' ? JSON.parse(read('youle_desktop/package.json')).version :
  contract.surface === 'mobile' ? read('apps/mobile/pubspec.yaml').match(/^version:\s*(\S+)/m)[1] : source_sha;
const action_versions = {};
const adapters={windows:['open_settings','set_theme','open_usage','open_indicators','set_indicator','open_candle_settings','set_candle_colors'],mobile:['open_settings','set_theme','open_usage','open_indicators','set_indicator'],website:['web_navigate']};
for (const f of contract.features) {
  if (!f.sources?.length || !['approved','pending','disabled'].includes(f.status) || !f.body?.trim()) throw Error('Incomplete support feature');
  if (f.status === 'approved') for (const [k,v] of Object.entries(f.actions)) {
    if(!adapters[contract.surface].includes(k))throw Error('New operation requires an implemented platform adapter');
    if (!Number.isSafeInteger(v) || v < 1 || (action_versions[k] && action_versions[k] !== v)) throw Error('Conflicting adapter version');
    action_versions[k] = v;
  }
}
const contract_id = hash(canonical(contract));
const source_hashes = Object.fromEntries([...new Set(contract.features.flatMap(f=>f.sources))].sort().map(p=>[p,hash(read(p))]));
const bundle = {schema_version:1,repository:contract.repository,source_sha,version,contract_id,contract,source_hashes};
const runtime = {support_protocol:2,contract_id,action_versions};
let path, content;
if (contract.surface === 'windows') {
  path='youle_desktop/src/renderer/support-runtime.ts';
  content='// Generated by tools/support_knowledge.py; edit support/catalog.json.\nexport const supportRuntime = '+JSON.stringify(runtime,null,2)+' as const;\n';
} else if (contract.surface === 'mobile') {
  path='apps/mobile/lib/features/auth/support_runtime.dart';
  content='// Generated by tools/support_knowledge.py; edit support/catalog.json.\nconst supportRuntime = <String, Object>'+JSON.stringify(runtime,null,2)+';\n';
} else {
  path='youle-ai_index/js/support-runtime.js';
  Object.assign(runtime,{version:'development',channel:'production'});
  content='// Generated by tools/support_knowledge.py; stamped during publication.\nwindow.HaoloSupportRuntime = '+JSON.stringify(runtime,null,2)+';\n';
}
if (process.argv.includes('--check')) {
  if (read(path) !== content) throw Error('Stale support runtime; run node tools/prepare-support.mjs');
} else writeFileSync(resolve(root,path),content,'utf8');
const i=process.argv.indexOf('--output');
if (i >= 0) {
  const target=resolve(process.argv[i+1]);mkdirSync(dirname(target),{recursive:true});
  writeFileSync(target,canonical(bundle)+'\n','utf8');
}
console.log(JSON.stringify({id:hash(canonical(bundle)),source_sha,contract_id,version,features:contract.features.length,status:'candidate'}));
