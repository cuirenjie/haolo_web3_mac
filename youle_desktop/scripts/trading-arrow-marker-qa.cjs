// Real mouse input against the production drawing controller, isolated data/profile.
const { app, BrowserWindow } = require('electron');
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..'), output = path.join(root, '.cache', 'arrow-marker-qa');
fs.mkdirSync(output, { recursive: true });
app.setPath('userData', path.join(output, 'profile'));
app.disableHardwareAcceleration();
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
let win;
(async () => {
  setTimeout(() => app.exit(1), 90000).unref();
  await app.whenReady();
  win = new BrowserWindow({ show: false, width: 1304, height: 880, webPreferences: { offscreen: true, backgroundThrottling: false } });
  const js = code => win.webContents.executeJavaScript(code, true);
  const settle = async () => { await js('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))'); await pause(50); };
  const input = (type, point) => win.webContents.sendInputEvent({ type, ...point, button: 'left', clickCount: 1 });
  const move = async point => { input('mouseMove', point); await settle(); };
  const click = async point => { await move(point); input('mouseDown', point); input('mouseUp', point); await settle(); };
  const drag = async (from, to) => { await move(from); input('mouseDown', from); await move(to); input('mouseUp', to); await settle(); };
  const capture = async name => fs.writeFileSync(path.join(output, name + '.png'), (await win.webContents.capturePage()).toPNG());
  const ready = async () => {
    for (let i = 0; i < 120 && !await js('Boolean(window.ready)'); i++) await pause(100);
    assert.equal(await js('Boolean(window.ready)'), true, await js('String(window.qaError)'));
    await js(`document.querySelector('#host').style.cssText='width:100%;height:100%';window.d=workspace.drawingController;workspace.loadingHistory=true;d.magnetEnabled=false`);
    await settle();
  };
  const anchors = () => js('(d.draft??d.drawings[0]).points.map(p=>d.pointToScreen(p))');
  const geometry = () => js(`(()=>{const el=d.content.querySelector('.trading-drawing-arrow-marker');return {points:Array.from(el.points,p=>({x:p.x,y:p.y})),width:el.getBBox().width,height:el.getBBox().height}})()`);
  const center = selector => js(`(()=>{const r=d.content.querySelector(${JSON.stringify(selector)}).getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()`);
  const near = (actual, expected, label) => assert.ok(Math.hypot(actual.x-expected.x, actual.y-expected.y)<1.2, label+': '+JSON.stringify({actual,expected}));
  await win.loadURL(`http://127.0.0.1:${process.env.HAOLO_QA_PORT || 5183}/@fs/${path.join(root, 'test/fixtures/trading-chart-navigation.html').replaceAll('\\', '/')}`);
  await ready();
  await js(`d.drawings=[];d.persistDrawings();d.selectTool('arrow-marker')`); await settle();
  const rect = await js('(()=>{const r=d.overlay.getBoundingClientRect();return {x:r.x,y:r.y}})()');
  const screen = (x, y) => ({ x: Math.round(rect.x+x), y: Math.round(rect.y+y) });
  const tail = screen(260, 130), smallTip = screen(440, 240), largeTip = screen(620, 350);
  await click(tail);
  assert.equal(await js('d.drawings.length'), 0, 'first click leaves a draft');
  assert.equal(await js('d.draft.points.length'), 2);
  await move(smallTip); const small = await geometry(); const firstAnchors = await anchors();
  near(firstAnchors[0], { x: 260, y: 130 }, 'tail stays fixed after release');
  near(firstAnchors[1], { x: 440, y: 240 }, 'preview follows mouse without holding button');
  await capture('preview-small');
  await move(largeTip); const large = await geometry();
  assert.ok(Math.abs(large.width / small.width - 2)<0.02 && Math.abs(large.height / small.height - 2)<0.02, 'entire arrow doubles with distance');
  await capture('preview-large');
  await move(smallTip); assert.ok(Math.abs((await geometry()).width-small.width)<1, 'moving back shrinks arrow');
  await click(largeTip);
  assert.equal(await js('d.drawings.length===1&&!d.draft'), true, 'second click commits exactly one arrow');
  assert.equal(await js(`d.content.querySelectorAll('.trading-drawing-handle').length`), 2);
  assert.equal(await js(`d.axisMarkerLayer.querySelectorAll('[data-drawing-axis-price]').length`), 2);
  await capture('completed-light');
  const savedTail = await js('JSON.stringify(d.drawings[0].points[0])');
  await drag(await center('[data-drawing-handle-index="1"]'), screen(180, 340));
  assert.equal(await js('JSON.stringify(d.drawings[0].points[0])'), savedTail, 'tip drag preserves tail');
  near((await anchors())[1], { x: 180, y: 340 }, 'tip drag rotates and resizes');
  const savedTip = await js('JSON.stringify(d.drawings[0].points[1])');
  await drag(await center('[data-drawing-handle-index="0"]'), screen(350, 140));
  assert.equal(await js('JSON.stringify(d.drawings[0].points[1])'), savedTip, 'tail drag preserves tip');
  // Pick a point inside the broad head, away from the center line and handles.
  const interior = await js(`(()=>{const p=d.drawings[0].points.map(p=>d.pointToScreen(p)),a=p[0],b=p[1],dx=b.x-a.x,dy=b.y-a.y;const r=d.overlay.getBoundingClientRect();return {x:Math.round(r.x+a.x+dx*.8-dy*.1),y:Math.round(r.y+a.y+dy*.8+dx*.1)}})()`);
  await js('d.selectDrawing(null)'); await settle();
  await click(interior);
  assert.equal(await js('d.selectedDrawingId===d.drawings[0].id'), true, 'filled head can select arrow');
  const beforeMove = await anchors();
  await drag(interior, { x: interior.x+65, y: interior.y+30 });
  const afterMove = await anchors();
  beforeMove.forEach((p,i)=>near(afterMove[i], { x:p.x+65,y:p.y+30 }, 'body drag moves both anchors'));
  await js(`d.drawings[0].locked=true;d.redraw()`); await settle();
  const locked = await js('JSON.stringify(d.drawings[0].points)');
  await drag(await center('[data-drawing-handle-index="1"]'), screen(600, 420));
  assert.equal(await js('JSON.stringify(d.drawings[0].points)'), locked, 'locked arrow cannot resize');
  await js(`d.drawings[0].locked=false;d.drawings[0].color='#f23645';d.persistDrawings();d.redraw()`); await settle();
  const stored = await js('JSON.stringify(d.drawings[0])');
  await win.reload(); await ready();
  assert.equal(await js('JSON.stringify(d.drawings[0].points)'), locked, 'both anchors survive reload');
  assert.equal(await js('d.drawings[0].color'), '#f23645');
  await js(`window.savedRange=d.getChart().timeScale().getVisibleLogicalRange();d.getChart().timeScale().setVisibleLogicalRange({from:savedRange.from+10,to:savedRange.to-10});d.redraw()`); await settle();
  assert.equal(await js('JSON.stringify(d.drawings[0].points)'), locked, 'chart zoom preserves time/price anchors');
  assert.ok((await geometry()).points.every(p=>Number.isFinite(p.x)&&Number.isFinite(p.y)));
  await js('d.getChart().timeScale().setVisibleLogicalRange(savedRange);d.redraw()'); await settle();
  await js(`d.selectDrawing(d.drawings[0].id);document.documentElement.dataset.theme='dark';workspace.applyChartTheme()`); await settle(); await capture('completed-dark');
  await js(`d.selectTool('arrow-marker')`); await click(screen(400, 180)); await move(screen(700, 300));
  await js(`document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))`); await settle();
  assert.equal(await js('!d.draft&&d.drawings.length===1'),true,'Escape cancels an unfinished arrow');
  // Legacy persisted glyphs gain two real anchors and retain identity/style.
  await js(`d.drawings=[{...JSON.parse(${JSON.stringify(stored)}),id:'legacy-arrow',points:[JSON.parse(${JSON.stringify(stored)}).points[0]]}];d.persistDrawings()`);
  await win.reload(); await ready();
  assert.equal(await js('d.drawings[0].points.length'),2,'legacy single anchor upgraded');
  assert.equal(await js('d.drawings[0].id'), 'legacy-arrow');
  await js('d.selectDrawing(d.drawings[0].id)'); await settle();
  await drag(await center('[data-drawing-handle-index="1"]'), screen(720, 300));
  near((await anchors())[1],{x:720,y:300},'legacy arrow tip is editable');
  await capture('legacy-resized');
  await js('d.undo()'); await settle();
  assert.equal(await js('d.drawings.length'),0,'undo removes arrow');
  await js('d.redo()'); await settle();
  assert.equal(await js('d.drawings.length'),1,'redo restores arrow');
  await js('d.selectDrawing(d.drawings[0].id);d.deleteSelectedDrawing()'); await settle();
  assert.equal(await js('d.drawings.length'),0,'delete removes arrow');
  assert.equal(await js('String(window.qaError||"")'),'');
  fs.writeFileSync(path.join(output,'report.json'),JSON.stringify({result:'PASS',checks:['two-click placement','live grow/shrink','two endpoint drags','filled-head selection','whole-arrow drag','lock','color and reload','chart zoom','light/dark','Escape cancellation','legacy migration and resize','delete, undo and redo']},null,2));
  console.log('PASS: arrow placement, scaling, editing, persistence, themes and legacy recovery');
  win.destroy(); app.quit();
})().catch(error=>{console.error(error);fs.writeFileSync(path.join(output,'failure.txt'),String(error.stack));win?.destroy();app.exit(1)});
