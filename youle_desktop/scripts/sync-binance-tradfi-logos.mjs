// Refresh public Binance originals; never redraw, recolor or resize the source files.
import { mkdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const directory = path.join(root, "src/renderer/assets/binance-tradfi");
const endpoints = {
  contracts: "https://fapi.binance.com/fapi/v1/exchangeInfo",
  logos: "https://www.binance.com/bapi/apex/v1/public/apex/marketing/futures/asset/logo",
  spotAssets: "https://www.binance.com/bapi/asset/v2/public/asset/asset/get-all-asset",
};
// Exact image filenames observed on Binance's Stocks list (2026-10-26).
// Some differ from futures logos, notably SpaceX's full wordmark.
const stockFiles = {
  MU: "MU.png", NVDA: "NVDA.png", SPCX: "SPCX-7c71.png", AAPL: "AAPL.png",
  TSLA: "TSLA-de59.png", SNDK: "SNDK-3d94.png", META: "META.png", AMD: "AMD.png",
  MSFT: "MSFT.png", BE: "BE.png", AMZN: "AMZN.png", INTC: "INTC.png", AVGO: "AVGO.png",
  WDC: "WDC.png", MRNA: "MRNA.png", STX: "STX.png", PLTR: "PLTR.png", CRWD: "CRWD.png",
  GOOG: "GOOG-fca8.jpeg", GEV: "GEV.png", MRVL: "MRVL-72f5.png", LITE: "LITE.png",
  LRCX: "LRCX.png", LLY: "LLY.png", MSTR: "MSTR-d6e4.png", AMAT: "AMAT.png",
  CRWV: "CRWV.png", PANW: "PANW.png", NFLX: "NFLX.png", ORCL: "ORCL.png", KORU: "KORU.png",
};

async function json(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(30_000) });
  if (!response.ok) throw Error(`${response.status}: ${url}`);
  return response.json();
}
const [contracts, logos, spotAssets] = await Promise.all(Object.values(endpoints).map(json));
const originals = new Map(logos.data.filter(item => item.logo).map(item => [item.asset, item.logo]));
const tradfi = contracts.symbols.filter(item => item.contractType === "TRADIFI_PERPETUAL" || item.underlyingSubType?.includes("TradFi"));
const assets = new Set([...tradfi.map(item => item.baseAsset), ...Object.keys(stockFiles)]);
const urls = Object.fromEntries([...assets].sort().map(asset => {
  const url = stockFiles[asset] ? `https://bin.bnbstatic.com/static/stock/${stockFiles[asset]}` : originals.get(asset);
  if (!url) throw Error(`Missing official logo: ${asset}`);
  return [asset, url];
}));
const aliases = {};
for (const item of spotAssets.data.filter(item => item.tags?.includes("bStocks"))) {
  const underlying = item.uq === "BRK.B" ? "BRKB" : item.uq === "SKHY" ? "SKHYNIX" : item.uq;
  if (urls[underlying]) aliases[item.assetCode] = underlying;
}
const gold = spotAssets.data.find(item => item.assetCode === "XAUT");
if (gold?.logoUrl) urls.XAUT = gold.logoUrl;
const entries = Object.entries(urls).sort(([a], [b]) => a.localeCompare(b));
const files = {};
let position = 0;
await mkdir(directory, { recursive: true });
await Promise.all(Array.from({ length: 4 }, async () => {
  while (position < entries.length) {
    const [asset, url] = entries[position++];
    if (!/^[A-Z0-9]+$/.test(asset) || !["bin.bnbstatic.com", "public.bnbstatic.com"].includes(new URL(url).hostname)) throw Error(`Unexpected source: ${asset}`);
    const response = await fetch(url, { signal: AbortSignal.timeout(30_000) });
    const bytes = Buffer.from(await response.arrayBuffer());
    const png = bytes.subarray(0, 8).equals(Buffer.from([137,80,78,71,13,10,26,10]));
    const jpeg = bytes[0] === 255 && bytes[1] === 216 && bytes[2] === 255;
    if (!response.ok || (!png && !jpeg) || bytes.length > 1_000_000) throw Error(`Invalid original: ${asset}`);
    const file = `${asset}.${png ? "png" : "jpg"}`;
    await writeFile(path.join(directory, file), bytes);
    files[asset] = { file, source: url, sha256: createHash("sha256").update(bytes).digest("hex") };
  }
}));
const ordered = Object.fromEntries(entries.map(([asset]) => [asset, files[asset]]));
await writeFile(path.join(directory, "sources.json"), JSON.stringify({ retrievedAt: new Date().toISOString(), endpoints, stockPage: "https://www.binance.com/en/markets/tradfi", assets: ordered, aliases }, null, 2) + "\n");
const records = Object.entries(ordered).map(([asset, entry]) => {
  const type = tradfi.find(item => item.baseAsset === asset)?.underlyingType;
  const kind = type === "COMMODITY" || asset === "XAUT" ? "commodity" : type === "FX" || type === "FOREX" ? "forex" : "equity";
  return `  ${JSON.stringify(asset)}: { kind: "${kind}", src: new URL("./assets/binance-tradfi/${entry.file}", import.meta.url).href, original: ${JSON.stringify(entry.source)} },`;
}).join("\n");
await writeFile(path.join(root, "src/renderer/trading-tradfi-logo-assets.ts"), `// Generated by scripts/sync-binance-tradfi-logos.mjs. Originals and SHA-256: assets/binance-tradfi/sources.json.\nexport const BINANCE_TRADFI_LOGOS: Readonly<Record<string, { kind: "commodity" | "forex" | "equity"; src: string; original: string }>> = {\n${records}\n};\n\nexport const BINANCE_TRADFI_LOGO_ALIASES: Readonly<Record<string, string>> = ${JSON.stringify(aliases, null, 2)};\n`);
console.log(`Saved ${entries.length} official originals and ${Object.keys(aliases).length} explicit spot aliases.`);
