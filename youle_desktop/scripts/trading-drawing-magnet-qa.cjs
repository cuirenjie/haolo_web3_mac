// Real chart APIs and Electron DOM, synthetic candles, isolated user profile.
// Run against this checkout's Vite server with HAOLO_QA_PORT (default 5183).
const { app, BrowserWindow } = require('electron');
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..'), output = path.join(root, '.cache', 'drawing-magnet-qa');
fs.mkdirSync(output, { recursive: true });
app.setPath('userData', path.join(output, 'profile'));
app.disableHardwareAcceleration();
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
(async () => {
  setTimeout(() => app.exit(1), 90000).unref();
  await app.whenReady();
  const win = new BrowserWindow({ show: false, width: 1304, height: 880, webPreferences: { offscreen: true, backgroundThrottling: false } });
  const js = async code => {
    const result = await win.webContents.executeJavaScript(`(async()=>{try{return {value:await eval(${JSON.stringify(code)})}}catch(e){return {error:String(e.stack)}}})()`, true);
    if (result.error) throw Error(result.error);
    return result.value;
  };
  const settle = () => js('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))');
  const capture = async name => fs.writeFileSync(path.join(output, name + '.png'), (await win.webContents.capturePage()).toPNG());
  const fixture = `http://127.0.0.1:${process.env.HAOLO_QA_PORT || 5183}/@fs/${path.join(root, 'test/fixtures/trading-chart-navigation.html').replaceAll('\\', '/')}`;
  const load = async () => {
    await win.loadURL(fixture);
    for (let i = 0; i < 150 && !await js('Boolean(window.ready)'); i++) await pause(100);
    assert.equal(await js('Boolean(window.ready)'), true, await js('String(window.qaError)'));
    await js(`window.w=workspace;window.d=w.drawingController;host.style.cssText='width:100%;height:100vh';
      clearInterval(w.pollTimer);clearInterval(w.candlePollTimer);w.favoriteTickerGeneration++;w.closeFavoriteTickerStreams();w.closeSocket();w.cancelScheduledLiveChartPaint();w.loadingHistory=true;`);
    await settle();
  };
  await win.webContents.session.clearStorageData();
  await load();
  const result = await js(`(async()=>{
    const checks=[]; const check=(ok,label)=>{if(!ok)throw Error(label);checks.push(label)};
    const close=(a,b)=>Math.abs(a-b)<1e-6;
    const action=name=>d.toolbar.querySelector('[data-drawing-action="'+name+'"]');
    const menu=d.toolbar.querySelector('[data-drawing-tool-menu="magnet"]');
    const disclosure=d.toolbar.querySelector('[data-drawing-group-id="magnet"]');
    const mode=value=>{disclosure.click();menu.querySelector('[data-magnet-mode="'+value+'"]').click()};
    check(!d.magnetEnabled&&d.magnetMode==='weak'&&!d.snapToIndicators,'defaults');
    disclosure.click();check(!menu.hidden&&disclosure.getAttribute('aria-expanded')==='true','disclosure opens menu');
    action('toggle-magnet-indicators').click();
    check(d.snapToIndicators&&!d.magnetEnabled&&!menu.hidden,'indicator toggle is independent and leaves menu open');
    document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
    check(menu.hidden&&document.activeElement===disclosure,'Escape dismisses and restores focus');
    mode('weak');check(d.magnetEnabled&&d.magnetMode==='weak'&&menu.hidden,'weak selection enables magnet');
    mode('strong');check(d.magnetEnabled&&d.magnetMode==='strong'&&action('toggle-magnet').querySelector('svg').dataset.drawingIcon==='magnet-strong','strong selection and toolbar icon');
    action('toggle-magnet').click();check(!d.magnetEnabled&&d.magnetMode==='strong','off remembers strength');
    action('toggle-magnet').click();check(d.magnetEnabled&&d.magnetMode==='strong','on restores strength');
    disclosure.click();
    document.dispatchEvent(new KeyboardEvent('keydown',{key:'End',bubbles:true,cancelable:true}));
    check(document.activeElement===action('toggle-magnet-indicators'),'keyboard navigation reaches switch');
    d.chartElement.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,button:2}));
    check(menu.hidden,'outside chart pointer closes menu');
    d.snapToIndicators=false;d.drawings=[];d.selectTool('crosshair');
    const sample=w.chartCandles.map(c=>({c,x:d.pointToScreen({time:c.time,price:c.close})?.x})).find(p=>p.x>250&&p.x<500);
    check(!!sample,'visible candle fixture');
    const {c,x}=sample, prices=[c.open,c.high,c.low,c.close];
    const ys=prices.map(p=>w.candleSeries.priceToCoordinate(p));
    const far=[45,d.plotBounds().height-45].find(y=>ys.every(py=>Math.abs(py-y)>40));
    check(far!==undefined,'far-away pointer fixture');
    const expected=prices[ys.reduce((best,y,i)=>Math.abs(y-far)<Math.abs(ys[best]-far)?i:best,0)];
    const event=(type,px,py,target=d.overlay,ctrl=false)=>{
      const r=d.chartElement.getBoundingClientRect();
      target.dispatchEvent(new PointerEvent(type,{bubbles:true,cancelable:true,pointerId:73,isPrimary:true,button:0,buttons:type==='pointerup'?0:1,clientX:r.left+px,clientY:r.top+py,ctrlKey:ctrl}));
    };
    const click=(px,py,ctrl=false)=>{event('pointerdown',px,py,d.overlay,ctrl);event('pointerup',px,py,d.overlay,ctrl)};
    mode('weak');d.selectTool('trend-line');click(x,far);
    check(close(d.draft.points[0].price,w.candleSeries.coordinateToPrice(far)),'weak far placement remains free');
    d.selectTool('crosshair');mode('strong');d.selectTool('trend-line');click(x,far);
    check(close(d.draft.points[0].price,expected)&&d.draft.points[0].time===c.time,'strong far placement snaps to OHLC');
    event('pointermove',x,far);d.flushPointerMoves();
    document.dispatchEvent(new KeyboardEvent('keydown',{key:'Control',ctrlKey:true,bubbles:true}));
    check(close(d.draft.points[1].price,w.candleSeries.coordinateToPrice(far))&&d.magnetEnabled,'Ctrl temporarily disables stationary preview');
    document.dispatchEvent(new KeyboardEvent('keyup',{key:'Control',bubbles:true}));
    check(close(d.draft.points[1].price,expected),'Ctrl release restores stationary snap');
    click(x+100,far);check(d.drawings.length===1&&!d.draft,'commit snapped line');
    const line=d.drawings[0];d.selectDrawing(line.id);d.redraw();
    const handle=d.content.querySelector('[data-drawing-handle-index="1"]'),start=d.pointToScreen(line.points[1]);
    event('pointerdown',start.x,start.y,handle);check(d.dragState?.mode==='handle','endpoint drag starts');
    event('pointermove',x,far);event('pointerup',x,far);
    check(close(line.points[1].price,expected)&&line.points[1].time===c.time,'endpoint drag uses strong magnet');
    line.points=[d.screenToDrawingPoint({x,y:far},false),d.screenToDrawingPoint({x:x+100,y:far+20},false)];
    d.selectDrawing(line.id);d.redraw();
    const original=JSON.stringify(line.points);
    let body=d.content.querySelector('[data-drawing-id="'+line.id+'"] line.trading-drawing-hit-target');
    event('pointerdown',x+20,far+4,body);check(d.dragState?.mode==='drawing','whole drawing drag starts');
    event('pointerup',x+20,far+4);
    check(JSON.stringify(line.points)===original,'selecting without movement does not snap an existing drawing');
    body=d.content.querySelector('[data-drawing-id="'+line.id+'"] line.trading-drawing-hit-target');
    const before=line.points.map(p=>d.pointToScreen(p));
    event('pointerdown',x+20,far+4,body);event('pointermove',x+120,far+34);event('pointerup',x+120,far+34);
    const after=line.points.map(p=>d.pointToScreen(p));
    check(close(after[1].x-after[0].x,before[1].x-before[0].x)&&close(after[1].y-after[0].y,before[1].y-before[0].y),'whole drawing snap preserves geometry');
    const bar=w.chartCandles.find(c=>c.time===line.points[0].time);
    check(!!bar&&[bar.open,bar.high,bar.low,bar.close].some(p=>close(p,line.points[0].price)),'whole drawing reference anchor snaps to OHLC');
    d.selectTool('crosshair');action('toggle-magnet').click();d.selectTool('trend-line');
    click(x,w.candleSeries.priceToCoordinate(c.high)-3,true);
    check(close(d.draft.points[0].price,c.high)&&!d.magnetEnabled,'Ctrl enables disabled magnet for placement');
    window.dispatchEvent(new Event('blur'));
    check(!d.magnetModifierHeld&&!d.magnetEnabled&&!d.draft,'blur clears temporary magnet and draft');
    w.activeMainIndicators=['ma'];w.updateMainIndicatorData(w.chartCandles);
    const ma=w.mainIndicatorSeries.get('ma')[0];
    const row=ma.dataByIndex(w.chart.timeScale().timeToIndex(c.time+d.timeOffsetSeconds,false));
    check(!!row&&Number.isFinite(row.value),'real MA data available');
    const sy=ma.priceToCoordinate(row.value),raw=d.screenToDrawingPoint({x,y:sy},false);
    d.magnetEnabled=true;d.magnetMode='strong';d.snapToIndicators=true;
    let snapped=d.screenToDrawingPoint({x,y:sy},true);
    check(close(snapped.price,row.value),'main chart snaps to actual MA series');
    w.mainIndicatorSeries.get('ma').forEach(s=>s.applyOptions({visible:false}));snapped=d.screenToDrawingPoint({x,y:sy},true);
    check(prices.some(p=>close(p,snapped.price)),'hidden MA excluded');w.mainIndicatorSeries.get('ma').forEach(s=>s.applyOptions({visible:true}));
    w.activeIndicators=['macd'];w.rebuildIndicatorPanes();w.updateIndicatorData(w.chartCandles);
    const pane=w.indicatorDrawingControllers.get('macd');
    check(!!pane,'indicator drawing controller available');
    w.activateDrawingController(pane);
    pane.magnetEnabled=true;pane.magnetMode='strong';pane.snapToIndicators=true;
    const plots=pane.getMagnetIndicatorSeries();
    const plot=plots.find(s=>s.dataByIndex(w.chart.timeScale().timeToIndex(c.time+pane.timeOffsetSeconds,false))?.value!==undefined);
    const study=plot.dataByIndex(w.chart.timeScale().timeToIndex(c.time+pane.timeOffsetSeconds,false));
    const py=plot.priceToCoordinate(study.value);
    const panePoint=pane.screenToDrawingPoint({x,y:py+1},true);
    check(close(pane.getCandleSeries().priceToCoordinate(panePoint.price),py),'MACD pane snaps on its own scale');
    pane.emitSharedToolState();
    check(d.magnetEnabled&&d.magnetMode==='strong'&&d.snapToIndicators,'pane changes synchronize settings');
    w.activateDrawingController(d);d.saveMagnetPreferences();d.selectTool('crosshair');
    disclosure.click();
    const rect=menu.getBoundingClientRect();
    check(rect.top>=0&&rect.bottom<=innerHeight&&rect.right<=innerWidth,'menu remains inside viewport');
    return {checks,passed:true};
  })()`);
  await settle();await capture('light');
  await js(`document.documentElement.dataset.theme='dark';w.applyChartTheme()`);
  await settle();await capture('dark');
  assert.equal(await js(`getComputedStyle(d.toolbar.querySelector('[data-magnet-mode="strong"]')).backgroundColor`),'rgb(229, 231, 235)','dark selection contrast');
  await js(`(async()=>{const language=await import('/app-language.mjs');document.documentElement.dataset.language='en';language.localizeAppTree(document.body,'en')})()`);
  await settle();await capture('english');
  assert.equal(await js(`d.toolbar.querySelector('[data-drawing-action="toggle-magnet-indicators"]').textContent.trim()`),'Snap to indicators');
  await load();
  assert.deepEqual(await js('({enabled:d.magnetEnabled,mode:d.magnetMode,snapToIndicators:d.snapToIndicators})'), {enabled:true,mode:'strong',snapToIndicators:true});
  await js(`w.splitLayoutId='2-columns';w.applySplitLayout()`);
  for(let i=0;i<100&&!await js('Boolean(w.splitPanes[0]?.candles.length)');i++)await pause(100);
  await js(`window.split=w.splitPanes[0];split.activateIndicator('main','ma');w.activateDrawingController(split.drawingController)`);
  await settle();
  assert.equal(await js(`(()=>{
    const controller=split.drawingController;
    if(!controller.magnetEnabled||controller.magnetMode!=='strong'||!controller.snapToIndicators)return false;
    const series=controller.getMagnetIndicatorSeries()[0];
    const row=series.data().find(p=>{const x=split.chart.timeScale().timeToCoordinate(p.time);return x>100&&x<300});
    if(!row)return false;
    const x=split.chart.timeScale().timeToCoordinate(row.time),y=series.priceToCoordinate(row.value);
    const point=controller.screenToDrawingPoint({x,y},true);
    return Math.abs(point.price-row.value)<1e-6;
  })()`),true,'split chart uses its own indicator data');
  // Native mouse delivery through the shared toolbar must target the active pane.
  const position=await js(`(()=>{const r=d.toolbar.querySelector('[data-drawing-action="toggle-magnet"]').getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()`);
  for(const type of ['mouseMove','mouseDown','mouseUp'])win.webContents.sendInputEvent({type,...position,button:'left',clickCount:1});
  await settle();
  assert.equal(await js('!split.drawingController.magnetEnabled&&!d.magnetEnabled'),true,'native toolbar click synchronizes split and main');
  result.checks.push('dark selection contrast','English menu localization','preferences survive full reload','split chart snaps to its own indicator data','native shared-toolbar click synchronizes split and main');
  fs.writeFileSync(path.join(output,'report.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result));win.destroy();app.exit(0);
})().catch(e=>{console.error(e);app.exit(1)});
